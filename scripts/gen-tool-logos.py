#!/usr/bin/env python3
"""Embeds the tool logos in the app as Swift data (Sources/AIKeeper/ToolLogoData.swift), so nothing has to be packaged next to the binary.
Sources are in assets/tool-logos: the open Simple Icons marks (SVG, drawn black on transparent so the app can tint them) and the
tools' own app icons. Run: python3 scripts/gen-tool-logos.py"""
import base64, os
root = os.path.join(os.path.dirname(__file__), "..")
png = os.path.join(root, "assets", "tool-logos", "png")
TEMPLATE = {"claude", "codex", "gemini", "git", "cursor", "opencode", "pi"}   # monochrome marks; the rest are full colour icons
lines = ["// Generated by scripts/gen-tool-logos.py. Do not edit.", "import Foundation", "",
         "enum ToolLogoData {", "    /// id: (base64 PNG, true when it is a one-colour mark the app tints)", "    static let all: [String: (png: String, template: Bool)] = ["]
for f in sorted(os.listdir(png)):
    if not f.endswith(".png"): continue
    n = f[:-4]
    b = base64.b64encode(open(os.path.join(png, f), "rb").read()).decode()
    lines.append(f'        "{n}": ("{b}", {"true" if n in TEMPLATE else "false"}),')
lines += ["    ]", "}", ""]
open(os.path.join(root, "Sources", "AIKeeper", "ToolLogoData.swift"), "w").write("\n".join(lines))
print("wrote", len(lines) - 8, "logos")
